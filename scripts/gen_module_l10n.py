def merge(locale: str, overrides: dict[str, str], with_meta: bool) -> dict:
    out: dict = {"@@locale": locale}
    for k, v in EN.items():
        if k == "@@locale":
            continue
        out[k] = overrides.get(k, v)
        if with_meta and k in PLACEHOLDERS:
            out[f"@{k}"] = {"placeholders": PLACEHOLDERS[k]}
    return out


def write_arb(name: str, data: dict) -> None:
    path = L10N / name
    path.write_text(json.dumps(data, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    n = sum(1 for k in data if not k.startswith("@"))
    print(f"wrote {name} ({n} message keys)")


